import React, { useEffect, useState } from 'react';
import {
  Award,
  BookOpen,
  Compass,
  Flame,
  GraduationCap,
  Plus,
  Scale,
  Shield,
  Wrench,
  Zap,
} from 'lucide-react';
import { PANTHEON_CODEX } from '../engine/pantheonEngine';
import {
  CookieJarVictory,
  IfThenContract,
  MarkUpgradeEntry,
  PantheonBriefing,
  RealDecisionRecord,
  SimulatorStats,
  TeachingLesson,
  TeachingProgressEntry,
} from '../engine/types';
import { playTacticalChime } from '../services/audioBiofeedback';
import { triggerHaptic } from '../services/vaultStorage';
import { DecisionTribunalView } from './DecisionTribunalView';
import { MasterySimulatorView } from './MasterySimulatorView';
import { TeachingsAcademyView } from './TeachingsAcademyView';

export type PantheonSubView =
  | 'ACADEMIA'
  | 'SIMULADOR'
  | 'TRIBUNAL'
  | 'STARK'
  | 'MAQUIAVEL'
  | 'GOGGINS'
  | 'CODICE';

interface Props {
  bioDayId: string;
  initialSubView?: PantheonSubView;
  teachingProgress: Record<string, TeachingProgressEntry>;
  completedFieldMissions?: Record<string, string>;
  simulatorStats?: SimulatorStats;
  decisionJournal?: RealDecisionRecord[];
  ifThenContracts: IfThenContract[];
  markLogs: MarkUpgradeEntry[];
  cookieJar: CookieJarVictory[];
  onCompleteLessonQuiz: (lesson: TeachingLesson, wasCorrect: boolean) => void;
  onToggleFieldMission: (lessonId: string) => void;
  onFinishSimulation: (score1000: number, rankTitle: string) => void;
  onSaveDecision?: (record: RealDecisionRecord) => void;
  onResolveDecision?: (
    decisionId: string,
    outcome: 'SUCESSO' | 'FALHA',
    lessonLearned: string,
  ) => void;
  onAddIfThen: (contract: IfThenContract) => void;
  onTriggerIfThen: (id: string) => void;
  onAddMarkLog: (log: MarkUpgradeEntry) => void;
  onAddCookie: (entry: CookieJarVictory) => void;
}

export const PantheonTab: React.FC<Props> = ({
  bioDayId,
  initialSubView = 'ACADEMIA',
  teachingProgress,
  completedFieldMissions = {},
  simulatorStats,
  decisionJournal = [],
  ifThenContracts,
  markLogs,
  cookieJar,
  onCompleteLessonQuiz,
  onToggleFieldMission,
  onFinishSimulation,
  onSaveDecision,
  onResolveDecision,
  onAddIfThen,
  onTriggerIfThen,
  onAddMarkLog,
  onAddCookie,
}) => {
  const [subView, setSubView] = useState<PantheonSubView>(initialSubView);
  const [selectedMentor, setSelectedMentor] =
    useState<PantheonBriefing['mentorId']>('JESUS_CRISTO');

  useEffect(() => {
    setSubView(initialSubView);
  }, [initialSubView]);

  // Stark Mark N+1 state
  const [whatFailed, setWhatFailed] = useState('');
  const [rootCause, setRootCause] = useState('');
  const [mechanicalPatch, setMechanicalPatch] = useState('');

  // Maquiavel Se-Entao state
  const [cueIf, setCueIf] = useState('');
  const [actionThen, setActionThen] = useState('');
  const [preCommitment, setPreCommitment] = useState('');

  // Cookie Jar manual victory
  const [cookieTitle, setCookieTitle] = useState('');
  const [cookieProof, setCookieProof] = useState('');

  const nextMarkLabel = `Mark 1.${markLogs.length + 1}`;

  const handleSaveMark = () => {
    if (!whatFailed.trim() || !mechanicalPatch.trim()) return;
    triggerHaptic('success');
    playTacticalChime('VICTORY');
    onAddMarkLog({
      id: `mk_${Date.now()}`,
      bioDayId,
      versionLabel: nextMarkLabel,
      failureWhatHappened: whatFailed.trim(),
      rootCause: rootCause.trim() || 'Fricção ambiental não blindada previamente.',
      systemPatchInstalled: mechanicalPatch.trim(),
    });
    setWhatFailed('');
    setRootCause('');
    setMechanicalPatch('');
  };

  const handleSaveIfThen = () => {
    if (!cueIf.trim() || !actionThen.trim()) return;
    triggerHaptic('success');
    onAddIfThen({
      id: `ift_${Date.now()}`,
      triggerSituation: cueIf.trim().startsWith('SE') ? cueIf.trim() : `SE ${cueIf.trim()}`,
      shieldedAction: actionThen.trim().startsWith('ENTÃO')
        ? actionThen.trim()
        : `ENTÃO ${actionThen.trim()}`,
      machiavelliPreCommitment:
        preCommitment.trim() || 'Barreira física configurada com antecedência.',
      timesTriggered: 0,
      active: true,
    });
    setCueIf('');
    setActionThen('');
    setPreCommitment('');
  };

  const handleSaveCookie = () => {
    if (!cookieTitle.trim() || !cookieProof.trim()) return;
    triggerHaptic('success');
    playTacticalChime('VICTORY');
    onAddCookie({
      id: `cj_${Date.now()}`,
      bioDayId,
      title: cookieTitle.trim(),
      hardContext: cookieProof.trim(),
      autoGenerated: false,
    });
    setCookieTitle('');
    setCookieProof('');
  };

  const codexItem = PANTHEON_CODEX.find((c) => c.id === selectedMentor) ?? PANTHEON_CODEX[0];

  return (
    <>
      <div className="chip-row">
        <button
          className={`chip ${subView === 'ACADEMIA' ? 'chip-active' : ''}`}
          onClick={() => setSubView('ACADEMIA')}
        >
          <GraduationCap size={13} style={{ verticalAlign: 'middle' }} /> Base Absoluta (200)
        </button>
        <button
          className={`chip ${subView === 'SIMULADOR' ? 'chip-active' : ''}`}
          onClick={() => setSubView('SIMULADOR')}
        >
          <Compass size={13} style={{ verticalAlign: 'middle' }} /> Simulador Zero→Mestre
        </button>
        <button
          className={`chip ${subView === 'TRIBUNAL' ? 'chip-active' : ''}`}
          onClick={() => setSubView('TRIBUNAL')}
        >
          <Scale size={13} style={{ verticalAlign: 'middle' }} /> Decidir (Salomão)
        </button>
        <button
          className={`chip ${subView === 'GOGGINS' ? 'chip-active' : ''}`}
          onClick={() => setSubView('GOGGINS')}
        >
          <Flame size={13} style={{ verticalAlign: 'middle' }} /> Cookie Jar (Goggins)
        </button>
        <button
          className={`chip ${subView === 'MAQUIAVEL' ? 'chip-active' : ''}`}
          onClick={() => setSubView('MAQUIAVEL')}
        >
          <Shield size={13} style={{ verticalAlign: 'middle' }} /> Se-Então (Maquiavel)
        </button>
        <button
          className={`chip ${subView === 'STARK' ? 'chip-active' : ''}`}
          onClick={() => setSubView('STARK')}
        >
          <Wrench size={13} style={{ verticalAlign: 'middle' }} /> Mark N+1 (Stark)
        </button>
        <button
          className={`chip ${subView === 'CODICE' ? 'chip-active' : ''}`}
          onClick={() => setSubView('CODICE')}
        >
          <BookOpen size={13} style={{ verticalAlign: 'middle' }} /> Os 12 Mentores
        </button>
      </div>

      {subView === 'ACADEMIA' && (
        <TeachingsAcademyView
          bioDayId={bioDayId}
          progressMap={teachingProgress}
          completedFieldMissions={completedFieldMissions}
          onCompleteLessonQuiz={onCompleteLessonQuiz}
          onToggleFieldMission={onToggleFieldMission}
          onOpenSimulator={() => setSubView('SIMULADOR')}
        />
      )}

      {subView === 'SIMULADOR' && (
        <MasterySimulatorView
          simulatorStats={simulatorStats}
          progressMap={teachingProgress}
          completedFieldMissions={completedFieldMissions}
          onFinishSimulation={onFinishSimulation}
          onCompleteLessonQuiz={onCompleteLessonQuiz}
          onToggleFieldMission={onToggleFieldMission}
        />
      )}

      {subView === 'TRIBUNAL' && (
        <DecisionTribunalView
          bioDayId={bioDayId}
          records={decisionJournal}
          onSaveDecision={(rec) => onSaveDecision?.(rec)}
          onResolveDecision={onResolveDecision}
        />
      )}

      {subView === 'GOGGINS' && (
        <div className="card card-amber">
          <div className="section-header">
            <div>
              <div className="section-kicker">
                David Goggins • Autoeficácia de Bandura &amp; Plasticidade aMCC
              </div>
              <h2 className="section-title">
                Cookie Jar — Cofre de Provas Reais ({cookieJar.length})
              </h2>
            </div>
            <Award size={22} color="var(--amber)" />
          </div>

          <p className="muted" style={{ marginTop: 0 }}>
            Motivação barata evapora sob dor ou fadiga. O córtex pré-frontal recupera tração quando
            acessa <strong>memórias episódicas verificáveis</strong> de momentos em que você não
            recuou.
          </p>

          <div className="field">
            <label>Registrar Vitória Difícil da Sua História ou de Hoje</label>
            <input
              className="input"
              placeholder="Ex: Passei na prova trabalhando 10h/dia / Treinei sob chuva..."
              value={cookieTitle}
              onChange={(e) => setCookieTitle(e.target.value)}
            />
          </div>
          <div className="field">
            <label>Prova Factual do Custo Superado</label>
            <input
              className="input"
              placeholder="Qual obstáculo real você venceu sem negociar desistência?"
              value={cookieProof}
              onChange={(e) => setCookieProof(e.target.value)}
            />
          </div>
          <button className="btn btn-primary btn-block" onClick={handleSaveCookie}>
            <Plus size={16} /> Selar Prova Real no Cookie Jar
          </button>

          <div style={{ marginTop: 16, display: 'flex', flexDirection: 'column', gap: 10 }}>
            {[...cookieJar].reverse().map((c) => (
              <div key={c.id} className="metric-box">
                <div style={{ display: 'flex', justifyContent: 'space-between', gap: 8 }}>
                  <strong>{c.title}</strong>
                  <span className="mono muted" style={{ fontSize: 11 }}>
                    {c.bioDayId}
                  </span>
                </div>
                <div className="muted" style={{ marginTop: 4 }}>
                  {c.hardContext}
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

      {subView === 'MAQUIAVEL' && (
        <div className="card card-cyan">
          <div className="section-header">
            <div>
              <div className="section-kicker" style={{ color: 'var(--cyan)' }}>
                Maquiavel (Virtù vs Fortuna) • Gollwitzer 642 Testes (d = 0.65)
              </div>
              <h2 className="section-title">Contratos Pré-Decididos Se-Então</h2>
            </div>
            <Shield size={22} color="var(--cyan)" />
          </div>

          <p className="muted" style={{ marginTop: 0 }}>
            Maquiavel escreveu que a Fortuna inunda tudo apenas onde não se construíram diques
            antes da tempestade. Automatize sua reação ao sabotador antes que o cansaço chegue.
          </p>

          <div className="field">
            <label>Gatilho de Sabotagem (SE...)</label>
            <input
              className="input"
              placeholder="SE eu chegar exausto às 19h querendo ir para o sofá..."
              value={cueIf}
              onChange={(e) => setCueIf(e.target.value)}
            />
          </div>
          <div className="field">
            <label>Resposta Automática Pré-Decidida (ENTÃO...)</label>
            <input
              className="input"
              placeholder="ENTÃO visto o tênis sem sentar e executo os primeiros 5 minutos..."
              value={actionThen}
              onChange={(e) => setActionThen(e.target.value)}
            />
          </div>
          <div className="field">
            <label>Dique Físico de Maquiavel (Pré-compromisso no ambiente)</label>
            <input
              className="input"
              placeholder="Ex: Roupa de treino já separada na porta às 07h..."
              value={preCommitment}
              onChange={(e) => setPreCommitment(e.target.value)}
            />
          </div>
          <button className="btn btn-primary btn-block" onClick={handleSaveIfThen}>
            <Plus size={16} /> Construir Dique Se-Então
          </button>

          <div style={{ marginTop: 16, display: 'flex', flexDirection: 'column', gap: 10 }}>
            {ifThenContracts.map((ct) => (
              <div key={ct.id} className="metric-box">
                <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: 6 }}>
                  <span className="badge badge-cyan">Dique Ativo</span>
                  <span className="mono" style={{ fontSize: 12, color: 'var(--emerald)' }}>
                    Acionado {ct.timesTriggered}x
                  </span>
                </div>
                <div style={{ fontSize: 13.5, fontWeight: 700 }}>{ct.triggerSituation}</div>
                <div className="muted" style={{ marginTop: 3 }}>
                  {ct.shieldedAction}
                </div>
                <div className="muted" style={{ fontSize: 12, marginTop: 4, marginBottom: 8 }}>
                  <strong>Pré-compromisso:</strong> {ct.machiavelliPreCommitment}
                </div>
                <button
                  className="btn btn-ghost btn-block"
                  style={{ minHeight: 36, fontSize: 12.5 }}
                  onClick={() => {
                    triggerHaptic('medium');
                    onTriggerIfThen(ct.id);
                  }}
                >
                  <Zap size={14} color="var(--amber)" /> Acionei Este Dique Hoje (+1 Virtù)
                </button>
              </div>
            ))}
          </div>
        </div>
      )}

      {subView === 'STARK' && (
        <div className="card card-amber">
          <div className="section-header">
            <div>
              <div className="section-kicker">
                Tony Stark • Engenharia Reversa de Falhas (Zero Culpa Emocional)
              </div>
              <h2 className="section-title">Protocolo {nextMarkLabel}</h2>
            </div>
            <Wrench size={22} color="var(--amber)" />
          </div>

          <p className="muted" style={{ marginTop: 0 }}>
            Quando a Mark II congelou na estratosfera, Stark não se chicoteou: ele trocou a liga
            metálica e construiu a Mark III. Trate qualquer falha de rotina como bug de sistema.
          </p>

          <div className="field">
            <label>1. Qual falha real aconteceu? (Fato sem drama)</label>
            <input
              className="input"
              placeholder="Ex: Pulei a sessão de foco / Dormi 3h mais tarde..."
              value={whatFailed}
              onChange={(e) => setWhatFailed(e.target.value)}
            />
          </div>
          <div className="field">
            <label>2. Causa-Raiz Estrutural</label>
            <input
              className="input"
              placeholder="Ex: Deixei notificações abertas na mesa de estudo..."
              value={rootCause}
              onChange={(e) => setRootCause(e.target.value)}
            />
          </div>
          <div className="field">
            <label>3. Patch Mecânico Permanente da Próxima Versão</label>
            <input
              className="input"
              placeholder="Ex: Celular fica em outro cômodo das 08h às 10h30..."
              value={mechanicalPatch}
              onChange={(e) => setMechanicalPatch(e.target.value)}
            />
          </div>
          <button className="btn btn-emerald btn-block" onClick={handleSaveMark}>
            Compilar Patch {nextMarkLabel}
          </button>

          <div style={{ marginTop: 16, display: 'flex', flexDirection: 'column', gap: 10 }}>
            {[...markLogs].reverse().map((m) => (
              <div key={m.id} className="metric-box">
                <div style={{ display: 'flex', justifyContent: 'space-between' }}>
                  <strong style={{ color: 'var(--amber)' }}>{m.versionLabel}</strong>
                  <span className="mono muted" style={{ fontSize: 11 }}>
                    {m.bioDayId}
                  </span>
                </div>
                <div className="muted" style={{ fontSize: 12.5, marginTop: 4 }}>
                  <strong>Bug:</strong> {m.failureWhatHappened}
                </div>
                <div style={{ fontSize: 13.2, marginTop: 4 }}>
                  <strong>Patch Instalado:</strong> {m.systemPatchInstalled}
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

      {subView === 'CODICE' && (
        <div className="card">
          <div className="section-kicker">A Pedra Angular &amp; Arquitetura Comparada</div>
          <h2 className="section-title" style={{ marginBottom: 12 }}>
            Os 12 Mestres &amp; Arquétipos da Forja
          </h2>

          <div className="chip-row" style={{ marginBottom: 14 }}>
            {PANTHEON_CODEX.map((item) => (
              <button
                key={item.id}
                className={`chip ${selectedMentor === item.id ? 'chip-active' : ''}`}
                onClick={() => {
                  triggerHaptic('light');
                  setSelectedMentor(item.id);
                }}
              >
                {item.name}
              </button>
            ))}
          </div>

          <div className="card card-amber" style={{ padding: 14 }}>
            <div className="section-kicker">{codexItem.domain}</div>
            <h3 className="section-title">{codexItem.name}</h3>
            <div className="muted" style={{ marginBottom: 8 }}>
              {codexItem.title}
            </div>
            <div className="badge badge-cyan" style={{ marginBottom: 10 }}>
              {codexItem.neuroAnchor}
            </div>
            <p style={{ margin: 0, fontSize: 14, lineHeight: 1.55 }}>
              <strong>Axioma Operacional:</strong> “{codexItem.maxim}”
            </p>
          </div>
        </div>
      )}
    </>
  );
};
