import React, { useMemo, useState } from 'react';
import { Activity, BarChart3, Brain, Crown, Dumbbell, Flame, HelpCircle, Shield } from 'lucide-react';
import { ChessArenaTab } from './components/chess/ChessArenaTab';
import { CommandTab } from './components/CommandTab';
import { CortexTab } from './components/CortexTab';
import { OnboardingWizard } from './components/OnboardingWizard';
import { PantheonSubView, PantheonTab } from './components/PantheonTab';
import { PhysicalForgeTab } from './components/PhysicalForgeTab';
import { QuickGuideModal } from './components/QuickGuideModal';
import { TelemetryVaultTab } from './components/TelemetryVaultTab';
import { ToastProvider } from './components/ToastProvider';
import { ThemeProvider, ThemeToggle } from './components/ThemeProvider';
import { resolveRealDecisionOutcome } from './engine/decisionTribunalEngine';
import { buildDemoVault, buildZeroSkillYouthVault } from './engine/demoScenario';
import {
  advanceQueueSlot,
  computeBioDayId,
  createInitialVault,
  evaluateEvolutionPhase,
  prescribeDayPlan,
} from './engine/stateEngine';
import { computeUpdatedTeachingProgress } from './engine/teachingsCatalog';
import {
  CognitiveChallengeLog,
  CookieJarVictory,
  DailyCheckIn,
  DeliberatePracticeLog,
  IfThenContract,
  MarkUpgradeEntry,
  TeachingLesson,
  UserProfile,
  VaultState,
  WorkoutSessionLog,
} from './engine/types';
import { loadVault, saveVault, triggerHaptic } from './services/vaultStorage';

type TabId = 'COMANDO' | 'FORJA' | 'CORTEX' | 'XADREZ' | 'PANTEAO' | 'TELEMETRIA';

export const AppInner: React.FC = () => {
  const [vault, setVault] = useState<VaultState>(() => loadVault());
  const [activeTab, setActiveTab] = useState<TabId>('COMANDO');
  const [pantheonSubView, setPantheonSubView] = useState<PantheonSubView>('ACADEMIA');
  const [editingProfile, setEditingProfile] = useState(false);
  const [showQuickGuide, setShowQuickGuide] = useState(false);

  const commitVault = (next: VaultState) => {
    setVault(next);
    saveVault(next);
  };

  const bioDayId = useMemo(
    () => computeBioDayId(new Date(), vault.profile),
    [vault.profile?.usualWakeTime],
  );

  const todayCheckIn = vault.checkIns[bioDayId];

  const todayPlan = useMemo(() => {
    if (!vault.profile || !todayCheckIn) return null;
    return prescribeDayPlan(vault.profile, todayCheckIn, vault);
  }, [vault, todayCheckIn]);

  if (!vault.profile || editingProfile) {
    return (
      <OnboardingWizard
        initialProfile={editingProfile ? vault.profile : null}
        onCancelEdit={editingProfile ? () => setEditingProfile(false) : undefined}
        onLoadZeroYouth={() => {
          const zeroVault = buildZeroSkillYouthVault();
          commitVault(zeroVault);
          setEditingProfile(false);
          setActiveTab('COMANDO');
        }}
        onLoadDemo={() => {
          const demo = buildDemoVault();
          commitVault(demo);
          setEditingProfile(false);
          setActiveTab('COMANDO');
        }}
        onComplete={(profile: UserProfile, firstIfThen) => {
          const nextContracts = [...vault.contracts];
          if (firstIfThen) {
            nextContracts.unshift({
              id: `ift_init_${Date.now()}`,
              triggerSituation: firstIfThen.triggerSituation,
              shieldedAction: firstIfThen.shieldedAction,
              machiavelliPreCommitment: firstIfThen.machiavelliPreCommitment,
              timesTriggered: 0,
              active: true,
            });
          }
          commitVault({
            ...vault,
            profile,
            contracts: nextContracts,
          });
          setEditingProfile(false);
        }}
      />
    );
  }

  const amccCompletedToday = vault.cookieJar.some(
    (c) => c.bioDayId === bioDayId && c.autoGenerated && c.title.includes('aMCC'),
  );
  const restConfirmedToday = vault.ledger[bioDayId]?.status === 'REST_CONFIRMED';
  const completedWorkoutToday = [...vault.workouts]
    .reverse()
    .find((w) => w.bioDayId === bioDayId);
  const teachingProgress = vault.teachingProgress ?? {};
  const completedFieldMissions = vault.completedFieldMissions ?? {};

  const handleSaveCheckIn = (ci: DailyCheckIn) => {
    const tentativePlan = prescribeDayPlan(vault.profile!, ci, vault);
    const next: VaultState = {
      ...vault,
      checkIns: {
        ...vault.checkIns,
        [bioDayId]: ci,
      },
      lastRedZoneBioDayId:
        tentativePlan.readiness.zone === 'VERMELHO' ? bioDayId : vault.lastRedZoneBioDayId,
      lastViralSymptomBioDayId: ci.viralOrFeverSymptoms
        ? bioDayId
        : vault.lastViralSymptomBioDayId,
    };
    commitVault(next);
  };

  const handleConfirmRestDay = () => {
    commitVault({
      ...vault,
      ledger: {
        ...vault.ledger,
        [bioDayId]: {
          bioDayId,
          status: 'REST_CONFIRMED',
          internalLoadAu: 0,
          usedMinimumFloor: false,
        },
      },
    });
  };

  const handleCompleteAmcc = (title: string, description: string) => {
    if (amccCompletedToday) return;
    const entry: CookieJarVictory = {
      id: `cj_amcc_${Date.now()}`,
      bioDayId,
      title: `Desafio aMCC Vencido — ${title}`,
      hardContext: description,
      autoGenerated: true,
    };
    commitVault({
      ...vault,
      cookieJar: [...vault.cookieJar, entry],
    });
  };

  const handleCompleteWorkout = (
    log: WorkoutSessionLog,
    advanceSlot: boolean,
    usedMinimumFloor: boolean,
  ) => {
    const nextCookieJar = [...vault.cookieJar];
    if (usedMinimumFloor) {
      nextCookieJar.push({
        id: `cj_floor_${Date.now()}`,
        bioDayId,
        title: 'Hábito Mantido no Dia Difícil',
        hardContext: `Mesmo com pouco tempo ou energia, mantive a consistência ativa (${log.durationMinutes} min).`,
        autoGenerated: true,
      });
    }

    const updated: VaultState = {
      ...vault,
      nextQueueSlot: advanceSlot ? advanceQueueSlot(vault.nextQueueSlot) : vault.nextQueueSlot,
      workouts: [...vault.workouts, log],
      ledger: {
        ...vault.ledger,
        [bioDayId]: {
          bioDayId,
          status: 'LOGGED_ACTIVE',
          internalLoadAu: log.internalLoadAu,
          usedMinimumFloor,
        },
      },
      cookieJar: nextCookieJar,
    };

    const phaseCheck = evaluateEvolutionPhase(updated);
    updated.currentPhase = phaseCheck.phase;
    commitVault(updated);
  };

  const handleRecordMentalSession = () => {
    commitVault({
      ...vault,
      mentalSessionsCount: (vault.mentalSessionsCount ?? 0) + 1,
    });
  };

  const handleSaveDeliberateLog = (log: DeliberatePracticeLog) => {
    const updated: VaultState = {
      ...vault,
      deliberatePractice: [...vault.deliberatePractice, log],
    };
    updated.currentPhase = evaluateEvolutionPhase(updated).phase;
    commitVault(updated);
  };

  const handleSaveCognitiveLog = (log: CognitiveChallengeLog) => {
    const prevCog = vault.cognitiveLogs ?? [];
    const nextCookie = [...vault.cookieJar];
    if (log.score >= 850) {
      nextCookie.push({
        id: `cj_cog_${Date.now()}`,
        bioDayId,
        title: `Alto Desempenho Cognitivo (${log.score}/1000)`,
        hardContext: `Precisão de ${log.accuracyPct}% na Arena Mental (${log.challengeType}).`,
        autoGenerated: true,
      });
    }
    commitVault({
      ...vault,
      cognitiveLogs: [...prevCog, log],
      mentalSessionsCount: (vault.mentalSessionsCount ?? 0) + 1,
      cookieJar: nextCookie,
    });
  };

  const handleCompleteLessonQuiz = (lesson: TeachingLesson, wasCorrect: boolean) => {
    const prevMap = vault.teachingProgress ?? {};
    const prevCount = Object.keys(prevMap).length;
    const updatedEntry = computeUpdatedTeachingProgress(
      prevMap[lesson.id],
      wasCorrect,
      bioDayId,
      lesson.id,
    );
    const nextMap = {
      ...prevMap,
      [lesson.id]: updatedEntry,
    };
    const nextCount = Object.keys(nextMap).length;
    const nextCookie = [...vault.cookieJar];

    if (
      nextCount > prevCount &&
      (nextCount === 50 || nextCount === 100 || nextCount === 150 || nextCount === 200)
    ) {
      nextCookie.push({
        id: `cj_acad_${nextCount}_${Date.now()}`,
        bioDayId,
        title: `Marco da Base Absoluta: ${nextCount}/200 Lições Concluídas`,
        hardContext: `Domínio estruturado da Pedra Angular e dos 10 Pilares Universais.`,
        autoGenerated: true,
      });
    }

    commitVault({
      ...vault,
      teachingProgress: nextMap,
      mentalSessionsCount: (vault.mentalSessionsCount ?? 0) + 1,
      cookieJar: nextCookie,
    });
  };

  const handleToggleFieldMission = (lessonId: string) => {
    const current = { ...(vault.completedFieldMissions ?? {}) };
    if (current[lessonId]) {
      delete current[lessonId];
    } else {
      current[lessonId] = bioDayId;
    }
    commitVault({
      ...vault,
      completedFieldMissions: current,
    });
  };

  const handleFinishSimulation = (score1000: number, rankTitle: string) => {
    const prev = vault.simulatorStats ?? {
      bestScore: 0,
      completedRuns: 0,
      lastRankTitle: 'Marco Zero',
      lastCompletedBioDayId: '',
    };
    const nextBest = Math.max(prev.bestScore, score1000);
    const nextCookie = [...vault.cookieJar];
    if (score1000 >= 950 && prev.bestScore < 950) {
      nextCookie.push({
        id: `cj_sim_master_${Date.now()}`,
        bioDayId,
        title: 'Consagração no Simulador: Do Zero ao Mestre Polímata',
        hardContext: `Pontuação ${score1000}/1000 superando todos os 8 crisóis de vida real.`,
        autoGenerated: true,
      });
    }
    commitVault({
      ...vault,
      simulatorStats: {
        bestScore: nextBest,
        completedRuns: prev.completedRuns + 1,
        lastRankTitle: rankTitle,
        lastCompletedBioDayId: bioDayId,
      },
      cookieJar: nextCookie,
    });
  };

  const handleAddIfThen = (contract: IfThenContract) => {
    commitVault({
      ...vault,
      contracts: [contract, ...vault.contracts],
    });
  };

  const handleTriggerIfThen = (id: string) => {
    commitVault({
      ...vault,
      contracts: vault.contracts.map((c) =>
        c.id === id ? { ...c, timesTriggered: c.timesTriggered + 1 } : c,
      ),
    });
  };

  const handleAddMarkLog = (log: MarkUpgradeEntry) => {
    commitVault({
      ...vault,
      markUpgrades: [...vault.markUpgrades, log],
    });
  };

  const handleAddCookie = (entry: CookieJarVictory) => {
    commitVault({
      ...vault,
      cookieJar: [...vault.cookieJar, entry],
    });
  };

  const envLabel =
    vault.profile.equipment === 'CALISTENIA'
      ? 'Peso do Corpo'
      : vault.profile.equipment === 'CASA'
        ? 'Em Casa'
        : 'Academia';

  return (
    <div className="app-shell">
      {showQuickGuide && <QuickGuideModal onClose={() => setShowQuickGuide(false)} />}

      <header className="top-bar">
        <div className="brand-mark">
          <div className="brand-icon">
            <Flame size={20} />
          </div>
          <div>
            <div className="brand-title">FORJA • {vault.profile.codename}</div>
            <div className="brand-sub">
              Treino {vault.nextQueueSlot} • {envLabel} • v38.0.0
            </div>
          </div>
        </div>
        <div style={{ display: 'flex', alignItems: 'center', gap: 6 }}>
          <button
            type="button"
            className="chip"
            style={{ padding: '5px 10px', fontSize: 11.5 }}
            onClick={() => {
              triggerHaptic('light');
              setShowQuickGuide(true);
            }}
          >
            <HelpCircle size={13} style={{ verticalAlign: 'middle' }} /> Guia
          </button>
          <div className="phase-pill">FASE {vault.currentPhase}/5</div>
          <ThemeToggle />
        </div>
      </header>

      <main className="page-content">
        {activeTab === 'COMANDO' && (
          <CommandTab
            bioDayId={bioDayId}
            profile={vault.profile}
            existingCheckIn={todayCheckIn}
            plan={todayPlan}
            amccCompletedToday={amccCompletedToday}
            restConfirmedToday={restConfirmedToday}
            teachingProgress={teachingProgress}
            completedFieldMissions={completedFieldMissions}
            eveningReflections={vault.eveningReflections ?? {}}
            onSaveCheckIn={handleSaveCheckIn}
            onSaveEveningReflection={(entry) => {
              const prevRefs = vault.eveningReflections ?? {};
              const isNew = !prevRefs[entry.bioDayId];
              const nextRefs = { ...prevRefs, [entry.bioDayId]: entry };
              const totalRefs = Object.keys(nextRefs).length;
              const nextCookies = [...vault.cookieJar];
              if (isNew && totalRefs % 5 === 0) {
                nextCookies.push({
                  id: `cj_eve_${totalRefs}_${Date.now()}`,
                  bioDayId,
                  title: `${totalRefs} Noites de Exame & Paz no Leito`,
                  hardContext:
                    'Consciência sondada, gratidão registrada e mente descarregada antes do sono.',
                  autoGenerated: true,
                });
              }
              commitVault({
                ...vault,
                eveningReflections: nextRefs,
                cookieJar: nextCookies,
              });
            }}
            onConfirmRestDay={handleConfirmRestDay}
            onCompleteAmcc={handleCompleteAmcc}
            onCompleteLessonQuiz={handleCompleteLessonQuiz}
            onToggleFieldMission={handleToggleFieldMission}
            onGoToWorkout={() => setActiveTab('FORJA')}
            onGoToCortex={() => setActiveTab('CORTEX')}
            onGoToAcademy={() => {
              setPantheonSubView('ACADEMIA');
              setActiveTab('PANTEAO');
            }}
            onGoToSimulator={() => {
              setPantheonSubView('SIMULADOR');
              setActiveTab('PANTEAO');
            }}
            chessState={vault.chessState}
            onGoToChess={() => setActiveTab('XADREZ')}
            vault={vault}
            onUpdateVault={commitVault}
/>
        )}

        {activeTab === 'FORJA' && (
          <PhysicalForgeTab
            bioDayId={bioDayId}
            plan={todayPlan}
            pastWorkouts={vault.workouts}
            completedWorkoutToday={completedWorkoutToday}
            onCompleteWorkout={handleCompleteWorkout}
            onGoToCheckIn={() => setActiveTab('COMANDO')}
          />
        )}

        {activeTab === 'CORTEX' && (
          <CortexTab
            bioDayId={bioDayId}
            profile={vault.profile}
            mentalSessionsCount={vault.mentalSessionsCount ?? 0}
            practiceLogs={vault.deliberatePractice}
            cognitiveLogs={vault.cognitiveLogs ?? []}
            skillBlueprints={vault.skillBlueprints ?? []}
            teachingProgress={teachingProgress}
            completedFieldMissions={completedFieldMissions}
            onRecordMentalSession={handleRecordMentalSession}
            onSaveDeliberateLog={handleSaveDeliberateLog}
            onSaveCognitiveLog={handleSaveCognitiveLog}
            onSaveBlueprints={(next) =>
              commitVault({
                ...vault,
                skillBlueprints: next,
              })
            }
            onAddIfThen={handleAddIfThen}
            onCompleteLessonQuiz={handleCompleteLessonQuiz}
            onToggleFieldMission={handleToggleFieldMission}
          />
        )}

        {activeTab === 'XADREZ' && (
          <ChessArenaTab
            vault={vault}
            bioDayId={bioDayId}
            onUpdateVault={(updater) => commitVault(updater(vault))}
          />
        )}

        {activeTab === 'PANTEAO' && (
          <PantheonTab
            bioDayId={bioDayId}
            initialSubView={pantheonSubView}
            teachingProgress={teachingProgress}
            completedFieldMissions={completedFieldMissions}
            simulatorStats={vault.simulatorStats}
            decisionJournal={vault.decisionJournal ?? []}
            ifThenContracts={vault.contracts}
            markLogs={vault.markUpgrades}
            cookieJar={vault.cookieJar}
            onCompleteLessonQuiz={handleCompleteLessonQuiz}
            onToggleFieldMission={handleToggleFieldMission}
            onFinishSimulation={handleFinishSimulation}
            onSaveDecision={(record) => {
              const nextDecisions = [...(vault.decisionJournal ?? []), record];
              const nextCookies = [...vault.cookieJar];
              if (nextDecisions.length === 1 || nextDecisions.length % 5 === 0) {
                nextCookies.push({
                  id: `cj_dec_${nextDecisions.length}_${Date.now()}`,
                  bioDayId,
                  title: `Tribunal de Salomão: ${nextDecisions.length} Decisão(ões) Auditada(s)`,
                  hardContext: `${record.decisionTitle} (${record.maturityScore100}/100)`,
                  autoGenerated: true,
                });
              }
              commitVault({
                ...vault,
                decisionJournal: nextDecisions,
                cookieJar: nextCookies,
              });
            }}
            onResolveDecision={(decisionId, outcome, lessonLearned) => {
              const nextDecisions = (vault.decisionJournal ?? []).map((rec) =>
                rec.id === decisionId
                  ? resolveRealDecisionOutcome(rec, outcome, lessonLearned, bioDayId)
                  : rec,
              );
              commitVault({
                ...vault,
                decisionJournal: nextDecisions,
              });
            }}
            onAddIfThen={handleAddIfThen}
            onTriggerIfThen={handleTriggerIfThen}
            onAddMarkLog={handleAddMarkLog}
            onAddCookie={handleAddCookie}
          />
        )}

        {activeTab === 'TELEMETRIA' && (
          <TelemetryVaultTab
            bioDayId={bioDayId}
            vault={vault}
            onUpdateVault={commitVault}
            onEditProfile={() => setEditingProfile(true)}
            onLoadDemo={() => {
              commitVault(buildDemoVault());
              setActiveTab('COMANDO');
            }}
            onLoadZeroYouth={() => {
              commitVault(buildZeroSkillYouthVault());
              setActiveTab('COMANDO');
            }}
            onResetVault={() => {
              commitVault(createInitialVault());
              setActiveTab('COMANDO');
            }}
          />
        )}
      </main>

      <nav className="bottom-nav">
        <div className="bottom-nav-inner">
          {[
            { id: 'COMANDO' as const, label: 'Início', Icon: Activity },
            { id: 'FORJA' as const, label: 'Treino', Icon: Dumbbell },
            { id: 'CORTEX' as const, label: 'Mente', Icon: Brain },
            { id: 'XADREZ' as const, label: 'Xadrez', Icon: Crown },
            { id: 'PANTEAO' as const, label: 'Panteão', Icon: Shield },
            { id: 'TELEMETRIA' as const, label: 'Evolução', Icon: BarChart3 },
          ].map(({ id, label, Icon }) => (
            <button
              key={id}
              type="button"
              className={`nav-item ${activeTab === id ? 'nav-item-active' : ''}`}
              onClick={() => {
                triggerHaptic('light');
                setActiveTab(id);
              }}
            >
              <Icon size={19} />
              <span>{label}</span>
            </button>
          ))}
        </div>
      </nav>
    </div>
  );
};

export const App: React.FC = () => {
  return (
    <ThemeProvider>
      <ToastProvider>
        <AppInner />
      </ToastProvider>
    </ThemeProvider>
  );
};
